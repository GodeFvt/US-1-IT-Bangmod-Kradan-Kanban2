CREATE TABLE IF NOT EXISTS users (
    oid varchar(40) PRIMARY KEY,
    username varchar(50) NOT NULL UNIQUE,
    name varchar(100) NOT NULL,
    email varchar(150) NOT NULL UNIQUE,
    role varchar(20) NOT NULL DEFAULT 'STUDENT'
        CHECK (role IN ('LECTURER', 'STAFF', 'STUDENT'))
);

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS role varchar(20) NOT NULL DEFAULT 'STUDENT';

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'ck_users_role'
    ) THEN
        ALTER TABLE users ADD CONSTRAINT ck_users_role
            CHECK (role IN ('LECTURER', 'STAFF', 'STUDENT'));
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_users_username ON users(username);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email ON users(email);

CREATE TABLE IF NOT EXISTS user_credentials (
    user_oid varchar(40) PRIMARY KEY REFERENCES users(oid) ON DELETE CASCADE,
    password_hash varchar(255) NOT NULL
        CHECK (password_hash LIKE '$argon2%'),
    password_changed_on timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS oauth_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_oid varchar(40) NOT NULL REFERENCES users(oid) ON DELETE CASCADE,
    provider varchar(20) NOT NULL CHECK (provider IN ('GOOGLE')),
    provider_subject varchar(255) NOT NULL,
    email varchar(254),
    created_on timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_on timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_oauth_provider_subject UNIQUE (provider, provider_subject),
    CONSTRAINT uq_oauth_user_provider UNIQUE (user_oid, provider)
);

CREATE INDEX IF NOT EXISTS idx_oauth_accounts_user_oid ON oauth_accounts(user_oid);

CREATE OR REPLACE FUNCTION set_oauth_updated_timestamp()
RETURNS trigger AS $$
BEGIN
    NEW.updated_on = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_oauth_accounts_updated_on ON oauth_accounts;
CREATE TRIGGER trg_oauth_accounts_updated_on
BEFORE UPDATE ON oauth_accounts FOR EACH ROW EXECUTE FUNCTION set_oauth_updated_timestamp();

CREATE TABLE IF NOT EXISTS boards (
    boardid varchar(10) PRIMARY KEY,
    boardname varchar(200) NOT NULL,
    description varchar(500),
    iscustomstatus boolean NOT NULL DEFAULT false,
    oid varchar(40) NOT NULL REFERENCES users(oid),
    visibility varchar(10) NOT NULL DEFAULT 'PRIVATE'
        CHECK (visibility IN ('PUBLIC', 'PRIVATE')),
    createdon timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedon timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS collaboration (
    boardid varchar(10) NOT NULL REFERENCES boards(boardid) ON DELETE CASCADE,
    oid varchar(40) NOT NULL REFERENCES users(oid) ON DELETE CASCADE,
    access varchar(10) NOT NULL DEFAULT 'READ' CHECK (access IN ('READ', 'WRITE')),
    ispending boolean NOT NULL DEFAULT true,
    addedon timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (boardid, oid)
);

CREATE TABLE IF NOT EXISTS tasklimits (
    tasklimitid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maximumtask integer DEFAULT 10,
    islimit boolean NOT NULL DEFAULT false,
    boardid varchar(10) NOT NULL REFERENCES boards(boardid) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS taskstatus (
    statusid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statusname varchar(50) NOT NULL,
    statusdescription varchar(200),
    statuscolor varchar(10) DEFAULT '#828282',
    boardid varchar(10) REFERENCES boards(boardid) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tasklists (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(100) NOT NULL,
    description varchar(500),
    assignees varchar(30),
    statusid integer NOT NULL REFERENCES taskstatus(statusid),
    createdon timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedon timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    boardid varchar(10) NOT NULL REFERENCES boards(boardid) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS taskattachment (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename varchar(255),
    storedname varchar(255) UNIQUE,
    contenttype varchar(255),
    filedata bigint,
    uploadedat timestamptz DEFAULT CURRENT_TIMESTAMP,
    taskid integer NOT NULL REFERENCES tasklists(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_boards_oid ON boards(oid);
CREATE INDEX IF NOT EXISTS idx_collaboration_oid ON collaboration(oid);
CREATE INDEX IF NOT EXISTS idx_tasklimits_board_id ON tasklimits(boardid);
CREATE INDEX IF NOT EXISTS idx_taskstatus_board_id ON taskstatus(boardid);
CREATE INDEX IF NOT EXISTS idx_tasklists_board_id ON tasklists(boardid);
CREATE INDEX IF NOT EXISTS idx_tasklists_status_id ON tasklists(statusid);
CREATE INDEX IF NOT EXISTS idx_taskattachment_task_id ON taskattachment(taskid);

CREATE OR REPLACE FUNCTION set_updated_timestamp()
RETURNS trigger AS $$
BEGIN
    NEW.updatedon = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_boards_updated_on ON boards;
CREATE TRIGGER trg_boards_updated_on
BEFORE UPDATE ON boards FOR EACH ROW EXECUTE FUNCTION set_updated_timestamp();

DROP TRIGGER IF EXISTS trg_tasklists_updated_on ON tasklists;
CREATE TRIGGER trg_tasklists_updated_on
BEFORE UPDATE ON tasklists FOR EACH ROW EXECUTE FUNCTION set_updated_timestamp();

